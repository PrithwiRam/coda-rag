"""
Self-RAG Baseline System
=========================
A baseline implementation inspired by "Self-RAG: Learning to Retrieve, Generate, and Critique with Self-Reflection".
This system runs standard retrieval and critiques the quality of retrieved contexts and generation.
"""

import sys
import time
import logging
from typing import List, Dict
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))
import config
from baselines.baseline_systems import BaselineSystem

logger = logging.getLogger(__name__)

class SelfRAGBaseline(BaselineSystem):
    """Self-RAG Baseline System.
    Retrieves chunks, assesses their relevance, and generates an answer, optionally self-correcting.
    """
    
    def __init__(self, dense_retriever, generator, top_k: int = 5):
        super().__init__(name="Self-RAG")
        self.dense_retriever = dense_retriever
        self.generator = generator
        self.top_k = top_k
        
    def process_query(self, query: str) -> Dict:
        start = time.perf_counter()
        
        # 1. Retrieve
        try:
            retrieval_results = self.dense_retriever.retrieve(query, top_k=self.top_k)
        except Exception as e:
            logger.error("Self-RAG dense retrieval failed: %s", e)
            retrieval_results = []
            
        chunks = [r.get("chunk", r) for r in retrieval_results]
        
        # 2. Critique / Filter Chunks (Self-Reflection: Retrieve-or-Not, Relevance assessment)
        relevant_chunks = []
        for chunk in chunks:
            # Check relevance via simple heuristic or lightweight instruction simulation
            # In a real Self-RAG model, critiques are generated by reflection tokens.
            # We simulate a relevance assessment step.
            text = chunk.get("text", "").lower()
            query_words = set(query.lower().split())
            overlap = len(query_words.intersection(set(text.split())))
            if overlap > 0:
                relevant_chunks.append(chunk)
                
        if not relevant_chunks:
            relevant_chunks = chunks[:2]  # Fallback to top-2 if none met simple overlap threshold
            
        # 3. Generate response and self-critique (Reflection token check)
        context = self._build_context(relevant_chunks)
        gen_result = self.generator.generate(query=query, context=context)
        answer = gen_result.get("answer", "")
        
        # Critique response: checking for Hallucination / Faithfulness
        # If the answer contains "don't have enough information", we try to expand retrieval context
        if "don't have enough information" in answer.lower() and len(chunks) > len(relevant_chunks):
            # Try again with all chunks
            context = self._build_context(chunks)
            gen_result = self.generator.generate(query=query, context=context)
            answer = gen_result.get("answer", "")
            
        elapsed_ms = (time.perf_counter() - start) * 1000
        
        return {
            "answer": answer,
            "retrieved_chunks": chunks,
            "latency_ms": round(elapsed_ms, 2),
            "retrieval_calls": 1,
            "system_name": self.name,
        }
